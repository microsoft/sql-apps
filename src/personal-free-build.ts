import { createHash, randomUUID } from 'node:crypto';
import { copyFile, mkdir, readFile, readdir, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { build } from 'esbuild';
import { z } from 'zod';
import { parseBrowserConfig } from './browser-config.js';
import { run as execute, type Run } from './process.js';
import { toolingAsset, toolingRoot } from './runtime-roots.js';

const parameterType = z.enum(['nvarchar', 'uniqueidentifier', 'bit', 'int', 'datetime2']);
const routeSchema = z.strictObject({
  method: z.enum(['GET', 'POST', 'PUT', 'PATCH', 'DELETE']),
  path: z.string().regex(/^\/api\/[A-Za-z][A-Za-z0-9_/-]*$/),
  roles: z.array(z.enum(['owner', 'member'])).min(1).max(2)
    .refine(roles => new Set(roles).size === roles.length, 'Route roles must be unique').optional(),
  procedure: z.strictObject({
    name: z.string().regex(/^[A-Za-z][A-Za-z0-9_]{0,127}$/),
    parameters: z.record(z.string().regex(/^[A-Za-z][A-Za-z0-9_]{0,127}$/), parameterType),
  }),
});
const apiSchema = z.strictObject({
  version: z.literal(1),
  authenticationProvider: z.enum(['aad', 'github']),
  routes: z.array(routeSchema).min(1).superRefine((routes, context) => {
    const routeKeys = new Set<string>();
    const procedures = new Set<string>();
    for (const [index, route] of routes.entries()) {
      const key = `${route.method} ${route.path}`;
      if (routeKeys.has(key)) {
        context.addIssue({ code: 'custom', path: [index], message: `Duplicate personal-free route: ${key}` });
      }
      routeKeys.add(key);
      if (procedures.has(route.procedure.name)) {
        context.addIssue({
          code: 'custom', path: [index, 'procedure', 'name'],
          message: `Duplicate personal-free procedure: ${route.procedure.name}`,
        });
      }
      procedures.add(route.procedure.name);
    }
  }),
});

export interface PersonalFreeBuildManifest {
  version: 1;
  sourceHash: string;
  files: { path: string; sha256: string }[];
}

async function files(directory: string, base = directory): Promise<string[]> {
  const output: string[] = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isSymbolicLink()) throw new Error('Personal-free build inputs must not contain symbolic links');
    if (entry.isDirectory()) output.push(...await files(path, base));
    else if (entry.isFile()) output.push(path.slice(base.length + 1).replaceAll('\\', '/'));
  }
  return output.sort();
}

const digest = (value: Buffer | string) => createHash('sha256').update(value).digest('hex');

async function snapshots(directory: string) {
  const paths = (await files(directory)).filter(path => path !== 'personal-free-build.json');
  return Promise.all(paths.map(async path => ({
    path, sha256: digest(await readFile(join(directory, path))),
  })));
}

export async function verifyPersonalFreeArtifact(directory: string): Promise<PersonalFreeBuildManifest> {
  const manifest = z.strictObject({
    version: z.literal(1),
    sourceHash: z.string().regex(/^[a-f0-9]{64}$/),
    files: z.array(z.strictObject({ path: z.string(), sha256: z.string().regex(/^[a-f0-9]{64}$/) })),
  }).parse(JSON.parse(await readFile(join(directory, 'personal-free-build.json'), 'utf8')));
  const actual = await snapshots(directory);
  if (JSON.stringify(actual) !== JSON.stringify(manifest.files) ||
      digest(JSON.stringify(actual)) !== manifest.sourceHash ||
      !['deployment/database.dacpac', 'deployment/template.json', 'deployment/api.json']
        .every(path => actual.some(file => file.path === path))) {
    throw new Error('Approved personal-free artifact is incomplete or changed; run plan again');
  }
  return manifest;
}

export async function buildPersonalFreeArtifact(
  root: string,
  destination: string,
  run: Run = execute,
): Promise<PersonalFreeBuildManifest> {
  root = resolve(root);
  destination = resolve(destination);
  const api = apiSchema.parse(JSON.parse(await readFile(join(root, 'personal-free-api.json'), 'utf8')));
  const temporary = `${destination}.${randomUUID()}.tmp`;
  await rm(temporary, { recursive: true, force: true });
  await mkdir(join(temporary, 'static'), { recursive: true });
  await mkdir(join(temporary, 'api', 'dist'), { recursive: true });
  let published = false;
  try {
    const publicRoot = join(root, 'public');
    const assets = await files(publicRoot);
    for (const name of ['index.html', 'style.css', 'app.js', 'staticwebapp.config.json']) {
      if (!assets.includes(name)) throw new Error(`Personal-free static input is missing: ${name}`);
    }
    if (assets.includes('auth-config.json')) {
      throw new Error('public/auth-config.json is generated by the personal-free build; remove the source copy');
    }
    for (const name of assets) {
      const target = join(temporary, 'static', name);
      await mkdir(dirname(target), { recursive: true });
      await copyFile(join(publicRoot, name), target);
    }
    const readinessRoute = api.routes.find(route => {
      if (route.method !== 'GET' || Object.keys(route.procedure.parameters).length) return false;
      try {
        parseBrowserConfig({ mode: 'static-web-apps', provider: api.authenticationProvider, readinessPath: route.path });
        return true;
      } catch (error) {
        if (!(error instanceof Error && error.message === 'Invalid browser readiness path')) throw error;
        return false;
      }
    });
    if (!readinessRoute) throw new Error('Personal-free API requires a browser-compatible, no-parameter GET readiness route');
    const readinessPath = readinessRoute.path;
    if (api.routes.some(route => route.roles?.includes('member')) &&
        !(readinessRoute.roles ?? ['owner']).includes('member')) {
      throw new Error(`Members can call some routes, so the readiness route ${readinessPath} must also list "member" in roles`);
    }
    await writeFile(join(temporary, 'static', 'auth-config.json'), `${JSON.stringify({
      mode: 'static-web-apps',
      provider: api.authenticationProvider,
      readinessPath,
    })}\n`);
    const entry = `import { app } from '@azure/functions';
import { createPersonalFreeHandler, parsePersonalFreeBody } from './personal-free-app.js';
import { createProcedureRuntime } from './sql-procedure-runtime.js';
const routes = ${JSON.stringify(api.routes)};
const runtime = createProcedureRuntime(process.env, routes.map(route => route.procedure), {
  readinessProcedure: ${JSON.stringify(readinessRoute.procedure.name)},
});
const handler = createPersonalFreeHandler(routes, runtime);
app.http('sqlAppsApi', {
  route: '{*path}',
  methods: ['GET','POST','PUT','PATCH','DELETE'],
  authLevel: 'anonymous',
  handler: async request => {
    let body;
    if (!['GET','HEAD'].includes(request.method)) {
      const text = await request.text();
      try {
        body = text ? parsePersonalFreeBody(text) : undefined;
      } catch (error) {
        if (error instanceof Error && 'statusCode' in error && error.statusCode === 400) {
          return { status: 400, jsonBody: { error: error.message } };
        }
        throw error;
      }
    }
    const response = await handler({ method: request.method, url: request.url, headers: request.headers, body });
    return { status: response.status, headers: Object.fromEntries(response.headers.entries()), body: await response.text() };
  },
});\n`;
    await build({
      stdin: { contents: entry, resolveDir: join(toolingRoot, 'dist', 'src'), sourcefile: 'personal-free-entry.mjs' },
      bundle: true, platform: 'node', target: 'node22', format: 'cjs',
      external: ['@azure/functions-core'],
      outfile: join(temporary, 'api', 'dist', 'index.cjs'),
    });
    await writeFile(join(temporary, 'api', 'host.json'), `${JSON.stringify({
      version: '2.0',
      extensionBundle: { id: 'Microsoft.Azure.Functions.ExtensionBundle', version: '[4.*, 5.0.0)' },
    }, null, 2)}\n`);
    await writeFile(join(temporary, 'api', 'package.json'), `${JSON.stringify({
      name: 'sql-apps-personal-free-api',
      private: true,
      type: 'module',
      main: 'dist/index.cjs',
      engines: { node: '22' },
    }, null, 2)}\n`);
    const deployment = join(temporary, 'deployment');
    const sqlOutput = join(temporary, 'sql-build');
    await mkdir(deployment);
    await writeFile(join(deployment, 'api.json'), `${JSON.stringify(api)}\n`);
    await run('dotnet', ['build', join(root, 'sql', 'personal-free.sqlproj'), '--output', sqlOutput]);
    await copyFile(join(sqlOutput, 'personal-free.dacpac'), join(deployment, 'database.dacpac'));
    await rm(sqlOutput, { recursive: true, force: true });
    await run('az', ['bicep', 'build', '--file', toolingAsset('infra', 'personal-free.bicep'),
      '--outfile', join(deployment, 'template.json')]);
    const delivered = await snapshots(temporary);
    const manifest: PersonalFreeBuildManifest = {
      version: 1,
      sourceHash: digest(JSON.stringify(delivered)),
      files: delivered,
    };
    await writeFile(join(temporary, 'personal-free-build.json'), `${JSON.stringify(manifest, null, 2)}\n`);
    await mkdir(dirname(destination), { recursive: true });
    await rm(destination, { recursive: true, force: true });
    await rename(temporary, destination);
    published = true;
    return manifest;
  } finally {
    if (!published) await rm(temporary, { recursive: true, force: true });
  }
}
